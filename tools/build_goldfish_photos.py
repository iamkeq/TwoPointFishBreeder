"""Builds the goldfish sprite sheet from real photos (assets/fish/goldfish_photos/*.png,
already cut out, facing right) into assets/fish/goldfish_sheet.png and
scripts/goldfish_cells.gd. Varieties without a photo use a stand-in photo with a tint
(listed in STAND_INS).

Cutting a fish out of a source photo (one-off, see cut()):
    python tools/build_goldfish_photos.py cut <photo> <variety> [flip] [x0 y0 x1 y1] [bg=x0,y0,x1,y1 ...]
  uses OpenCV GrabCut seeded with the box (or the middle of the picture), with any bg= rects
  forced to background, and writes
  assets/fish/goldfish_photos/<variety>.png.
Rebuild the sheet:
    python tools/build_goldfish_photos.py
Photo credits are in assets/fish/CREDITS.md.
"""
import os
import sys

import cv2
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PHOTOS = os.path.join(ROOT, "assets", "fish", "goldfish_photos")
ORDER = ["common", "comet", "shubunkin", "fantail", "ryukin", "calico_fantail", "black_moor", "oranda",
         "panda", "ranchu", "lionhead", "bubble_eye", "telescope", "pearlscale", "celestial"]
# variety -> (photo to use instead, RGB multiplier) when there's no photo of its own.
STAND_INS = {}
CELL_W, CELL_H = 200, 120
COLS = 5


def cut(src, variety, flip=False, box=None, bg=()):
    img = cv2.imread(src, cv2.IMREAD_COLOR)
    if img is None:
        raise SystemExit("can't read " + src)
    h, w = img.shape[:2]
    if box is None:
        box = (int(w * 0.04), int(h * 0.06), int(w * 0.96), int(h * 0.94))
    x0, y0, x1, y1 = box
    # Outside the box is background; extra bg rects (bits of plant, bubbles) are too.
    mask = np.full((h, w), cv2.GC_BGD, np.uint8)
    mask[y0:y1, x0:x1] = cv2.GC_PR_FGD
    for bx0, by0, bx1, by1 in bg:
        mask[by0:by1, bx0:bx1] = cv2.GC_BGD
    bgd = np.zeros((1, 65), np.float64)
    fgd = np.zeros((1, 65), np.float64)
    cv2.grabCut(img, mask, None, bgd, fgd, 8, cv2.GC_INIT_WITH_MASK)
    fg = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    # Keep the biggest blob (the fish), fill holes, soften the edge a little.
    n, labels, stats, _ = cv2.connectedComponentsWithStats(fg)
    if n > 1:
        biggest = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
        fg = np.where(labels == biggest, 255, 0).astype(np.uint8)
    fg = cv2.morphologyEx(fg, cv2.MORPH_CLOSE, np.ones((7, 7), np.uint8))
    rgba = cv2.cvtColor(img, cv2.COLOR_BGR2RGBA)
    out = Image.fromarray(rgba)
    alpha = Image.fromarray(fg).filter(ImageFilter.GaussianBlur(1.2))
    out.putalpha(alpha)
    out = out.crop(out.getbbox())
    if flip:
        out = out.transpose(Image.FLIP_LEFT_RIGHT)
    os.makedirs(PHOTOS, exist_ok=True)
    path = os.path.join(PHOTOS, variety + ".png")
    out.save(path)
    print("wrote", path, out.size)


def build():
    rows = (len(ORDER) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (CELL_W * COLS, CELL_H * rows), (0, 0, 0, 0))
    cells = {}
    for i, name in enumerate(ORDER):
        src, mult = name, None
        if not os.path.exists(os.path.join(PHOTOS, name + ".png")) and name in STAND_INS:
            src, mult = STAND_INS[name]
        path = os.path.join(PHOTOS, src + ".png")
        if not os.path.exists(path):
            print("missing", name)
            continue
        fish = Image.open(path).convert("RGBA")
        scale = min((CELL_W - 8) / fish.width, (CELL_H - 8) / fish.height)
        fish = fish.resize((max(1, int(fish.width * scale)), max(1, int(fish.height * scale))), Image.LANCZOS)
        if mult:
            r, g, b, a = fish.split()
            r = r.point(lambda p: min(255, int(p * mult[0])))
            g = g.point(lambda p: min(255, int(p * mult[1])))
            b = b.point(lambda p: min(255, int(p * mult[2])))
            fish = Image.merge("RGBA", (r, g, b, a))
        x = (i % COLS) * CELL_W + (CELL_W - fish.width) // 2
        y = (i // COLS) * CELL_H + (CELL_H - fish.height) // 2
        sheet.paste(fish, (x, y), fish)
        cells[name] = [x, y, fish.width, fish.height]
    sheet.save(os.path.join(ROOT, "assets", "fish", "goldfish_sheet.png"))
    lines = ["extends RefCounted", "## Generated by tools/build_goldfish_photos.py: where each goldfish variety is on",
             "## assets/fish/goldfish_sheet.png ([x, y, w, h]). Don't edit by hand.", "", "const CELLS := {"]
    for k, r in cells.items():
        lines.append('\t"%s": [%d, %d, %d, %d],' % (k, r[0], r[1], r[2], r[3]))
    lines.append("}")
    with open(os.path.join(ROOT, "scripts", "goldfish_cells.gd"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("sheet:", len(cells), "goldfish")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "cut":
        args = sys.argv[2:]
        flip = "flip" in args
        bg = [tuple(int(n) for n in a[3:].split(",")) for a in args[2:] if a.startswith("bg=")]
        nums = [int(a) for a in args[2:] if a.lstrip("-").isdigit()]
        cut(args[0], args[1], flip, tuple(nums) if len(nums) == 4 else None, bg)
    else:
        build()
