"""Pack the pixel-art goldfish into the game.

Picks one sprite per variety from the shared pixel goldfish set
(G:/Game Ideas/_shared-assets/fish/goldfish-pixel/sprites, cut from the sheet by
_shared-assets/tools/cut_checker_sheet.py), copies them to assets/fish/goldfish_pixel/<variety>.png,
packs them into assets/fish/goldfish_pixel_sheet.png and writes scripts/goldfish_pixel_cells.gd.

    python tools/build_goldfish_pixel.py            # use the copies already in assets/fish/goldfish_pixel
    python tools/build_goldfish_pixel.py --from-shared   # re-copy from the shared set using PICKS

To swap a variety's picture, change its number in PICKS and run with --from-shared.
"""
import os, sys, shutil
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARED = os.path.join(os.path.dirname(ROOT), "_shared-assets", "fish", "goldfish-pixel", "sprites")
OUT_DIR = os.path.join(ROOT, "assets", "fish", "goldfish_pixel")

# variety -> sprite number on the shared sheet (01-30, left to right, top to bottom).
PICKS = {
	"common": 1, "comet": 28, "shubunkin": 25, "fantail": 12, "ryukin": 23,
	"calico_fantail": 4, "black_moor": 5, "oranda": 18, "panda": 8, "ranchu": 30,
	"lionhead": 17, "bubble_eye": 7, "telescope": 3, "pearlscale": 11, "celestial": 26,
}
COLS, PAD = 5, 4

if "--from-shared" in sys.argv:
	os.makedirs(OUT_DIR, exist_ok=True)
	for v, n in PICKS.items():
		shutil.copyfile(os.path.join(SHARED, "goldfish_%02d.png" % n), os.path.join(OUT_DIR, v + ".png"))

imgs = {v: Image.open(os.path.join(OUT_DIR, v + ".png")).convert("RGBA") for v in PICKS}
cw = max(i.width for i in imgs.values()) + PAD * 2
ch = max(i.height for i in imgs.values()) + PAD * 2
rows = (len(imgs) + COLS - 1) // COLS
sheet = Image.new("RGBA", (cw * COLS, ch * rows), (0, 0, 0, 0))
cells = {}
for k, (v, im) in enumerate(imgs.items()):
	x = (k % COLS) * cw + (cw - im.width) // 2
	y = (k // COLS) * ch + (ch - im.height) // 2
	sheet.paste(im, (x, y))
	cells[v] = [x, y, im.width, im.height]
sheet.save(os.path.join(ROOT, "assets", "fish", "goldfish_pixel_sheet.png"))
lines = ["extends RefCounted",
	"## Generated by tools/build_goldfish_pixel.py: where each goldfish variety is on",
	"## assets/fish/goldfish_pixel_sheet.png ([x, y, w, h]). Don't edit by hand.", "", "const CELLS := {"]
for v, c in cells.items():
	lines.append('\t"%s": [%d, %d, %d, %d],' % (v, *c))
lines.append("}")
with open(os.path.join(ROOT, "scripts", "goldfish_pixel_cells.gd"), "w", newline="\n") as f:
	f.write("\n".join(lines) + "\n")
print("packed %d goldfish, sheet %dx%d" % (len(cells), sheet.width, sheet.height))
